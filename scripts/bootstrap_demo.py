from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

DEFAULT_CATEGORIES = ("bottle", "metal_nut", "screw")


def run(*args: str) -> None:
    print("\n$", " ".join(args), flush=True)
    subprocess.run(args, check=True)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Build the complete local VisionGuard demo from selected MVTec AD categories."
    )
    parser.add_argument("--dataset-root", required=True, help="Directory containing bottle/, metal_nut/, screw/.")
    parser.add_argument("--categories", nargs="+", default=list(DEFAULT_CATEGORIES))
    parser.add_argument("--validation-ratio", type=float, default=0.40)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--model-dir", default="memory_bank")
    parser.add_argument("--artifact-dir", default="artifacts/runtime")
    parser.add_argument("--split-dir", default="datasets/splits")
    parser.add_argument("--config-output", default="model_config.json")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    root = Path(args.dataset_root)
    model_dir = Path(args.model_dir)
    artifact_dir = Path(args.artifact_dir)
    split_root = Path(args.split_dir)

    model_dir.mkdir(parents=True, exist_ok=True)
    artifact_dir.mkdir(parents=True, exist_ok=True)
    split_root.mkdir(parents=True, exist_ok=True)

    config = {"default_category": args.categories[0], "categories": {}}

    for category in args.categories:
        category_root = root / category
        train_good = category_root / "train" / "good"
        test_dir = category_root / "test"
        if not train_good.exists() or not test_dir.exists():
            raise SystemExit(f"Invalid MVTec category layout: {category_root}")

        split_dir = split_root / category
        bank_path = model_dir / f"{category}_hog_bank.npz"
        calibration_path = artifact_dir / f"{category}_calibration.json"
        evaluation_path = artifact_dir / f"{category}_final_evaluation.json"

        run(
            sys.executable,
            "scripts/prepare_validation_split.py",
            "--test-dir", str(test_dir),
            "--output-dir", str(split_dir),
            "--validation-ratio", str(args.validation_ratio),
            "--seed", str(args.seed),
        )
        run(
            sys.executable,
            "scripts/build_hog_bank.py",
            "--train-dir", str(train_good),
            "--output", str(bank_path),
        )
        run(
            sys.executable,
            "scripts/evaluate_patch_hog.py",
            "--data-dir", str(split_dir / "validation"),
            "--bank", str(bank_path),
            "--output", str(calibration_path),
        )

        calibration = json.loads(calibration_path.read_text(encoding="utf-8"))
        threshold = float(calibration["threshold"])

        run(
            sys.executable,
            "scripts/evaluate_patch_hog.py",
            "--data-dir", str(split_dir / "final_test"),
            "--bank", str(bank_path),
            "--threshold", str(threshold),
            "--output", str(evaluation_path),
        )

        config["categories"][category] = {
            "engine": "patch_hog",
            "memory_bank": str(bank_path).replace("\\", "/"),
            "threshold": threshold,
            "threshold_source": (
                f"Deterministic {args.validation_ratio:.0%} validation holdout by defect folder, "
                f"seed {args.seed}; generated by scripts/bootstrap_demo.py"
            ),
        }

    output = Path(args.config_output)
    output.write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
    print(f"\nDemo configuration written to {output}")
    print("Run: uvicorn webapp:app --host 0.0.0.0 --port 8000")


if __name__ == "__main__":
    main()
